// Builds paste-into-SQL-Editor scripts from the migrations.
//
// The SQL Editor runs a whole paste as ONE transaction, and Postgres refuses to use an enum
// value in the transaction that added it. Migrations that only add enum values
// (*_enums.sql) therefore end a script; everything after them goes into the next one.
//
//   supabase/setup-1.sql, setup-2.sql …   NEW empty project: run in order (last one includes seed)
//   supabase/upgrade-0005-0007.sql        already applied by the client (kept for reference)
//   supabase/upgrade-20261030-1.sql, -2   projects that already have 0001–0007: run in order
//   supabase/upgrade-20261102.sql         projects set up before 2 Nov: daily output → site diary
//   supabase/upgrade-20261103-N.sql       after upgrade-20261102: payments, costing, schedule editing (run in order)
//   supabase/upgrade-20261104.sql         after upgrade-20261103-N: payment certificate layout, company logo
//   supabase/upgrade-20261105-N.sql       after upgrade-20261104: calendar & holidays, photos, role features (run in order)
//
//   node supabase/build-sql.mjs

import { readFileSync, readdirSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = dirname(fileURLToPath(import.meta.url));
const mig = (f) => readFileSync(join(dir, 'migrations', f), 'utf8');
const files = readdirSync(join(dir, 'migrations')).filter((f) => f.endsWith('.sql')).sort();
const seed = readFileSync(join(dir, 'seed.sql'), 'utf8');
const section = (name, sql) => `\n\n-- >>>>>>>>>>>>>>>>>>>> ${name}\n\n${sql}`;

// Split a list of migration files into scripts that each end after an *_enums.sql file.
const split = (list) => {
  const parts = [[]];
  for (const f of list) {
    parts[parts.length - 1].push(f);
    if (/_enums\.sql$/.test(f)) parts.push([]);
  }
  return parts.filter((p) => p.length);
};

const header = (title, i, n, extra = '') => `-- =============================================================================
-- Site Materials Management — ${title} — script ${i} of ${n}
-- Paste into Supabase Dashboard → SQL Editor → Run. Run the scripts IN ORDER, each once.
-- Generated by supabase/build-sql.mjs — do not edit.${extra}
-- =============================================================================
`;

// ---- full setup for a new project ----------------------------------------
for (const f of readdirSync(dir)) if (/^setup(-\d+)?\.sql$/.test(f)) rmSync(join(dir, f));
const setupParts = split(files);
setupParts.forEach((part, i) => {
  const last = i === setupParts.length - 1;
  const body = part.map((f) => section(f, mig(f))).join('') + (last ? section('seed.sql', seed) : '');
  writeFileSync(join(dir, `setup-${i + 1}.sql`), header('NEW project setup', i + 1, setupParts.length,
    last ? `\n--\n-- Afterwards create your admin with supabase/create-admin.sql.` : '') + body);
});

// ---- upgrade for projects that already have 0001–0007 ---------------------
for (const f of readdirSync(dir)) if (/^upgrade-20261030(-\d+)?\.sql$/.test(f)) rmSync(join(dir, f));
const upParts = split(files.filter((f) => f >= '20261030'));
upParts.forEach((part, i) => {
  writeFileSync(join(dir, `upgrade-20261030-${i + 1}.sql`),
    header('UPGRADE (purchase/site-use flows, schedule & EVM, monthly look-ahead)', i + 1, upParts.length,
      '\n-- For projects that already ran setup.sql + upgrade-0005-0007.sql.') +
    part.map((f) => section(f, mig(f))).join(''));
});

// ---- upgrade for projects set up from setup-1/-2 before 2 Nov (daily output → site diary) ----------
const nov = files.filter((f) => f >= '20261102' && f < '20261103');
writeFileSync(join(dir, 'upgrade-20261102.sql'), header('UPGRADE (daily output → site diary)', 1, 1,
  '\n-- For projects already set up with setup-1.sql + setup-2.sql (or the 20261030 upgrade) before 2 Nov 2026.') +
  nov.map((f) => section(f, mig(f))).join('') + "\n\n-- Make the API see the new table straight away.\nnotify pgrst, 'reload schema';\n");

// ---- upgrade for projects already on the 2 Nov upgrade: payments, material costing, schedule editing … ----
for (const f of readdirSync(dir)) if (/^upgrade-20261103(-\d+)?\.sql$/.test(f)) rmSync(join(dir, f));
const nov3 = split(files.filter((f) => f >= '20261103' && f < '20261104')).filter((p) => p.length);
nov3.forEach((part, i) => {
  writeFileSync(join(dir, `upgrade-20261103-${i + 1}.sql`),
    header('UPGRADE (payments, material costing, schedule editing, elements from schedule)', i + 1, nov3.length,
      '\n-- For projects that already ran upgrade-20261102.sql.') +
    part.map((f) => section(f, mig(f))).join('') + "\n\nnotify pgrst, 'reload schema';\n");
});

// ---- upgrade for projects already on the 3 Nov upgrade: payment certificate layout, company logo ----
const nov4 = files.filter((f) => f >= '20261104' && f < '20261105');
writeFileSync(join(dir, 'upgrade-20261104.sql'), header('UPGRADE (payment certificate layout, company logo)', 1, 1,
  '\n-- For projects that already ran upgrade-20261103-1.sql and -2.sql. Safe to run again.') +
  nov4.map((f) => section(f, mig(f))).join('') + "\n\nnotify pgrst, 'reload schema';\n");

// ---- upgrade for projects already on the 4 Nov upgrade: calendar, photos, role features ----
for (const f of readdirSync(dir)) if (/^upgrade-20261105(-\d+)?\.sql$/.test(f)) rmSync(join(dir, f));
const nov5 = split(files.filter((f) => f >= '20261105'));
nov5.forEach((part, i) => {
  writeFileSync(join(dir, `upgrade-20261105-${i + 1}.sql`),
    header('UPGRADE (project calendar & holidays, site photos, role features)', i + 1, nov5.length,
      '\n-- For projects that already ran upgrade-20261104.sql. Safe to run again.') +
    part.map((f) => section(f, mig(f))).join('') + "\n\nnotify pgrst, 'reload schema';\n");
});

if (existsSync(join(dir, 'setup.sql'))) rmSync(join(dir, 'setup.sql'));
console.log(`setup: ${setupParts.length} scripts; upgrade-20261030: ${upParts.length} scripts; upgrade-20261102: ${nov.length} migration(s); upgrade-20261103: ${nov3.length} script(s); upgrade-20261104: ${nov4.length} migration(s); upgrade-20261105: ${nov5.length} script(s)`);
